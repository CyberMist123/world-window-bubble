  /**
   * 通用极坐标三维气泡绘制内核（同时支持命名主球与前景反相球 spec）
   */
  function paintPolarSpec(ctx, parsedSpec, ox, oy, cellSize, opts) {
    const options = opts || {};
    const stops = parsedSpec.stops;
    const radius = cellSize * (options.radiusRatio || parsedSpec.radiusRatio);
    const f0 = options.featherStart != null ? options.featherStart : parsedSpec.featherStart;
    const zeroTransparent = !!options.zeroTransparent;
    const rotRad = options.rotRad || 0;
    const alphaScale = options.alphaScale != null ? options.alphaScale : 1.0;
    const rimBoost = options.rimBoost != null ? options.rimBoost : 0.0;
    const grainAmp = options.grainAmp != null ? options.grainAmp : 0.85;

    const img = ctx.createImageData(cellSize, cellSize);
    const data = img.data;
    const half = (cellSize - 1) * 0.5;
    const allRings = parsedSpec.allRings;
    const alphaRings = parsedSpec.alphaRings;
    const numSegs = stops.length - 1;

    for (let py = 0; py < cellSize; py++) {
      const dy = py - half;
      for (let px = 0; px < cellSize; px++) {
        const dx = px - half;
        const dist = Math.hypot(dx, dy);
        const rnRaw = dist / radius;
        const idx = (py * cellSize + px) * 4;

        if (rnRaw >= 1.012) {
          if (zeroTransparent) {
            data[idx] = 0;
            data[idx + 1] = 0;
            data[idx + 2] = 0;
            data[idx + 3] = 0;
          } else {
            const angOut = Math.atan2(dy, dx) - rotRad;
            const rimCol = sampleAngularRingRgb(allRings[numSegs], angOut);
            data[idx] = Math.max(0, Math.min(255, Math.round(rimCol[0])));
            data[idx + 1] = Math.max(0, Math.min(255, Math.round(rimCol[1])));
            data[idx + 2] = Math.max(0, Math.min(255, Math.round(rimCol[2])));
            data[idx + 3] = 0;
          }
          continue;
        }

        const rn = Math.min(stops[numSegs], rnRaw);
        const ang = Math.atan2(dy, dx) - rotRad;

        let seg = 0;
        for (let k = 0; k < numSegs; k++) {
          if (rn >= stops[k]) seg = k;
        }
        const rStart = stops[seg];
        const rEnd = stops[seg + 1];
        const rt = rEnd > rStart ? Math.max(0, Math.min(1, (rn - rStart) / (rEnd - rStart))) : 0;
        const smoothRt = rt * rt * (3 - 2 * rt) * 0.30 + rt * 0.70;

        const ca = sampleAngularRingRgb(allRings[seg], ang);
        const cb = sampleAngularRingRgb(allRings[seg + 1], ang);

        const hash = Math.sin((px + ox) * 12.9898 + (py + oy) * 78.233) * 43758.5453;
        const grain = ((hash - Math.floor(hash)) - 0.5) * grainAmp;

        let rr = ca[0] + (cb[0] - ca[0]) * smoothRt + grain;
        let gg = ca[1] + (cb[1] - ca[1]) * smoothRt + grain;
        let bb = ca[2] + (cb[2] - ca[2]) * smoothRt + grain;

        // 强化水彩球外圈菲涅尔玻璃亮边与中心色彩通透度（抵消 31 抽头模糊对亮边的稀释）
        if (rimBoost > 0 && rnRaw > 0.70) {
          const rimT = Math.min(1, (rnRaw - 0.70) / 0.28);
          const fresnel = rimT * rimT * rimBoost;
          const lum = (rr * 0.299 + gg * 0.587 + bb * 0.114) / 255;
          // 仅提亮本身属于高光半球的奶油亮边，保留暗部水彩浓郁边缘对比
          const hiMask = Math.max(0, Math.min(1, (lum - 0.68) / 0.24));
          const lift = fresnel * hiMask;
          rr = rr + (255 - rr) * lift;
          gg = gg + (252 - gg) * lift;
          bb = bb + (242 - bb) * lift;
        }

        let alpha = 1.0;
        if (alphaRings) {
          const aa = sampleAngularRingScalar(alphaRings[seg], ang);
          const ab = sampleAngularRingScalar(alphaRings[seg + 1], ang);
          alpha = Math.max(0, Math.min(1, aa + (ab - aa) * smoothRt));
        }

        if (rnRaw >= 1.0) {
          alpha = 0.0;
        } else if (rnRaw > f0) {
          const t = (rnRaw - f0) / (1.0 - f0);
          alpha *= (1 - t * t * (3 - 2 * t));
        }

        alpha *= alphaScale;

        const rByte = Math.max(0, Math.min(255, Math.round(rr)));
        const gByte = Math.max(0, Math.min(255, Math.round(gg)));
        const bByte = Math.max(0, Math.min(255, Math.round(bb)));

        if (alpha <= 0.0015) {
          if (zeroTransparent) {
            data[idx] = 0;
            data[idx + 1] = 0;
            data[idx + 2] = 0;
          } else {
            data[idx] = rByte;
            data[idx + 1] = gByte;
            data[idx + 2] = bByte;
          }
          data[idx + 3] = 0;
        } else {
          data[idx] = rByte;
          data[idx + 1] = gByte;
          data[idx + 2] = bByte;
          data[idx + 3] = Math.round(alpha * 255);
        }
      }
    }

    if (options.compositeOver) {
      const tmp = document.createElement('canvas');
      tmp.width = cellSize;
      tmp.height = cellSize;
      tmp.getContext('2d').putImageData(img, 0, 0);
      ctx.drawImage(tmp, ox, oy);
    } else {
      // 直接 putImageData 写入未预乘 RGBA 字节，避免 Canvas 2D drawImage 预乘把透明外沿保护色抹成全黑 (0,0,0)
      ctx.putImageData(img, ox, oy);
    }
  }

