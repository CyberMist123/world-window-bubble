  /**
   * UNPACK_FLIP_Y_WEBGL=true 下的 2x2 图集坐标映射：
   * cell 0 -> suv(0, 0)     -> Canvas 左下 (0, cell)
   * cell 1 -> suv(0.5, 0)   -> Canvas 右下 (cell, cell)
   * cell 2 -> suv(0, 0.5)   -> Canvas 左上 (0, 0)
   * cell 3 -> suv(0.5, 0.5) -> Canvas 右上 (cell, 0)
   */
  function cell2x2Origin(index, cell) {
    const col = index % 2;
    const rowFromBottom = Math.floor(index / 2);
    return [col * cell, (1 - rowFromBottom) * cell];
  }

